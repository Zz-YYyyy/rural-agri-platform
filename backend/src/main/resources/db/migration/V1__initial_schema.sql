CREATE TABLE `stock_log` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '库存变动记录ID',
  `sku_id` BIGINT NOT NULL COMMENT '变动规格，关联product_sku.id',
  `order_item_id` BIGINT DEFAULT NULL COMMENT '订单预占或返还对应order_item.id；人工调整为空',
  `change_type` VARCHAR(32) NOT NULL COMMENT 'INITIAL初始库存 ORDER_RESERVE订单预占 ORDER_RELEASE订单返还 MANUAL_ADJUST人工增减',
  `quantity_delta` INT NOT NULL COMMENT '可售库存增减份数；预占为负，返还为正',
  `quantity_before` INT NOT NULL COMMENT '变动前可售库存',
  `quantity_after` INT NOT NULL COMMENT '变动后可售库存',
  `business_key` VARCHAR(128) NOT NULL COMMENT '库存动作幂等键，同一业务动作重试保持一致',
  `actor_type` VARCHAR(32) NOT NULL COMMENT 'USER买家 FARMER农户 ADMIN管理员 SYSTEM系统',
  `operator_user_id` BIGINT DEFAULT NULL COMMENT '人工操作者，关联sys_user.id；系统操作为空',
  `reason` VARCHAR(500) DEFAULT NULL COMMENT '库存变动说明',
  `occurred_at` DATETIME(3) NOT NULL COMMENT '业务实际发生时间',
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '记录写入时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_stock_business` (`business_key`),
  UNIQUE KEY `uk_stock_item_type` (`order_item_id`, `change_type`),
  KEY `idx_stock_sku_time` (`sku_id`, `occurred_at`, `id`),
  CONSTRAINT `ck_stock_type` CHECK (`change_type` IN ('INITIAL', 'ORDER_RESERVE', 'ORDER_RELEASE', 'MANUAL_ADJUST')),
  CONSTRAINT `ck_stock_quantity` CHECK (`quantity_before` >= 0 AND `quantity_after` >= 0 AND `quantity_after` = `quantity_before` + `quantity_delta`),
  CONSTRAINT `ck_stock_direction` CHECK ((`change_type` = 'INITIAL' AND `quantity_before` = 0 AND `quantity_delta` >= 0) OR (`change_type` = 'ORDER_RESERVE' AND `quantity_delta` < 0) OR (`change_type` = 'ORDER_RELEASE' AND `quantity_delta` > 0) OR (`change_type` = 'MANUAL_ADJUST' AND `quantity_delta` <> 0)),
  CONSTRAINT `ck_stock_item` CHECK ((`change_type` IN ('ORDER_RESERVE', 'ORDER_RELEASE') AND `order_item_id` IS NOT NULL) OR (`change_type` IN ('INITIAL', 'MANUAL_ADJUST') AND `order_item_id` IS NULL)),
  CONSTRAINT `ck_stock_actor` CHECK (`actor_type` IN ('USER', 'FARMER', 'ADMIN', 'SYSTEM')),
  CONSTRAINT `ck_stock_operator` CHECK ((`actor_type` = 'SYSTEM' AND `operator_user_id` IS NULL) OR (`actor_type` IN ('USER', 'FARMER', 'ADMIN') AND `operator_user_id` IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='可售库存变动流水，只追加不覆盖';

