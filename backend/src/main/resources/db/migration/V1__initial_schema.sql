  KEY `idx_ai_usage_budget_time` (`budget_state`, `created_at`),
  KEY `idx_ai_usage_currency_time` (`currency`, `created_at`),
  CONSTRAINT `ck_ai_usage_call_no` CHECK (`call_no` > 0),
  CONSTRAINT `ck_ai_usage_status` CHECK (`status` IN ('PREPARED', 'RUNNING', 'SUCCEEDED', 'FAILED', 'UNKNOWN')),
  CONSTRAINT `ck_ai_usage_source` CHECK (`usage_source` IN ('UNKNOWN', 'ESTIMATED', 'PROVIDER')),
  CONSTRAINT `ck_ai_usage_known_values` CHECK ((`usage_source` = 'UNKNOWN' AND `input_tokens` IS NULL AND `output_tokens` IS NULL AND `usage_details` IS NULL) OR (`usage_source` <> 'UNKNOWN' AND (`input_tokens` IS NOT NULL OR `output_tokens` IS NOT NULL OR `usage_details` IS NOT NULL))),
  CONSTRAINT `ck_ai_usage_tokens` CHECK ((`input_tokens` IS NULL OR `input_tokens` >= 0) AND (`output_tokens` IS NULL OR `output_tokens` >= 0)),
  CONSTRAINT `ck_ai_usage_details` CHECK (`usage_details` IS NULL OR JSON_TYPE(`usage_details`) = 'OBJECT'),
  CONSTRAINT `ck_ai_pricing_snapshot` CHECK (JSON_TYPE(`pricing_snapshot`) = 'OBJECT'),
  CONSTRAINT `ck_ai_cost_source` CHECK ((`cost_source` = 'UNKNOWN' AND `reported_cost` IS NULL AND `estimated_cost` IS NULL) OR (`cost_source` = 'PRICING_ESTIMATE' AND `estimated_cost` IS NOT NULL AND `reported_cost` IS NULL) OR (`cost_source` = 'PROVIDER' AND `reported_cost` IS NOT NULL)),
  CONSTRAINT `ck_ai_cost_nonnegative` CHECK ((`estimated_cost` IS NULL OR `estimated_cost` >= 0) AND (`reported_cost` IS NULL OR `reported_cost` >= 0) AND `reserved_cost` >= 0 AND `accounted_cost` >= 0),
  CONSTRAINT `ck_ai_budget_state` CHECK (`budget_state` IN ('RESERVED', 'UNRESOLVED', 'SETTLED', 'RELEASED')),
  CONSTRAINT `ck_ai_budget_retention` CHECK ((`budget_state` NOT IN ('RESERVED', 'UNRESOLVED') OR `accounted_cost` >= `reserved_cost`) AND (`budget_state` <> 'RELEASED' OR `accounted_cost` = 0)),
  CONSTRAINT `ck_ai_budget_settlement` CHECK (`budget_state` <> 'SETTLED' OR (`cost_source` = 'PROVIDER' AND `reported_cost` IS NOT NULL AND `accounted_cost` = `reported_cost`) OR (`cost_source` = 'PRICING_ESTIMATE' AND `estimated_cost` IS NOT NULL AND `accounted_cost` = `estimated_cost`)),
  CONSTRAINT `ck_ai_usage_times` CHECK ((`started_at` IS NULL OR `started_at` >= `created_at`) AND (`finished_at` IS NULL OR (`finished_at` >= `created_at` AND (`started_at` IS NULL OR `finished_at` >= `started_at`)))),
  CONSTRAINT `ck_ai_usage_lifecycle` CHECK ((`status` = 'PREPARED' AND `started_at` IS NULL AND `finished_at` IS NULL) OR (`status` = 'RUNNING' AND `started_at` IS NOT NULL AND `finished_at` IS NULL) OR (`status` IN ('SUCCEEDED', 'UNKNOWN') AND `started_at` IS NOT NULL AND `finished_at` IS NOT NULL) OR (`status` = 'FAILED' AND `finished_at` IS NOT NULL))
