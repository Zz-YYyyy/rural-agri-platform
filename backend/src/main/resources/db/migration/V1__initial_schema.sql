  `reconciled_at` DATETIME(3) NULL DEFAULT NULL COMMENT '最近人工或可靠账单核对时间',
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '调用准备记录时间',
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '状态或用量核对更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_ai_usage_call` (`call_id`),
