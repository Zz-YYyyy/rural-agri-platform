  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '模型调用记录主键',
  `conversation_id` BIGINT NOT NULL COMMENT '所属AI会话',
  `user_id` BIGINT NOT NULL COMMENT '所属平台账号，须与会话一致',
